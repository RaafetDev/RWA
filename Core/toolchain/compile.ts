import { basename } from "jsr:@std/path@1.0.9";
import { loadConfigFile, type RitaWappConfig } from "../config/config.ts";
import {
  INTEGRATED_MODULES,
  resolveEnabledModules,
} from "../modules/integrated/registry.ts";
import { getFrameworkRoot, getProjectRoot } from "./paths.ts";
import { compileVueProject } from "./compile_vue.ts";
import { logger } from "../cli/logger.ts";
import { BuildError } from "../cli/errors.ts";

export interface CompileOptions {
  projectDir?: string;
  isDev?: boolean;
}

function hexToCArray(hex: string): string {
  const bytes: string[] = [];
  for (let i = 0; i < hex.length; i += 2) {
    bytes.push(`0x${hex.slice(i, i + 2).toLowerCase()}`);
  }
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += 8) {
    lines.push("    " + bytes.slice(i, i + 8).join(", "));
  }
  return lines.join(",\n");
}

function hexToRgb(hex: string, fallback: { r: number; g: number; b: number }) {
  hex = (hex || "").replace(/^#/, "").trim();
  if (hex.length === 3) hex = hex.split("").map((c) => c + c).join("");
  if (hex.length !== 6) return fallback;
  const num = parseInt(hex, 16);
  if (isNaN(num)) return fallback;
  return { r: (num >> 16) & 0xff, g: (num >> 8) & 0xff, b: num & 0xff };
}

export async function compileProject(options: CompileOptions = {}): Promise<{
  exePath: string;
  bundlePath: string;
  appName: string;
}> {
  const frameworkRoot = getFrameworkRoot();
  const projectDir = getProjectRoot(options.projectDir);

  logger.info(`Compiling project in: ${projectDir}`);
  logger.debug(`Framework root: ${frameworkRoot}`);

  const cfg = await loadConfigFile(projectDir);
  const resolved = resolveEnabledModules(cfg.modules);

  const distBinDir = `${projectDir}/dist/bin`.replaceAll("\\", "/");
  await Deno.mkdir(distBinDir, { recursive: true });

  const projectDevDir = `${projectDir}/.dev`.replaceAll("\\", "/");
  await Deno.mkdir(projectDevDir, { recursive: true });

  const frameworkDevDir = `${frameworkRoot}/.dev`.replaceAll("\\", "/");
  await Deno.mkdir(frameworkDevDir, { recursive: true });

  // 1. Generate app_credentials.h
  const bg = hexToRgb(cfg.installer.backgroundColor, { r: 30, g: 30, b: 36 });
  const accent = hexToRgb(cfg.installer.accentColor, { r: 59, g: 130, b: 246 });
  const text = hexToRgb(cfg.installer.textColor, { r: 243, g: 244, b: 246 });

  const defaultKey =
    "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
  const aesKey = cfg.security.aesKey || defaultKey;
  const keyCArray = hexToCArray(aesKey);

  const moduleMacros = resolved.enabled
    .map((name) =>
      `#define RITA_MODULE_${
        name.toUpperCase().replace(/[^A-Z0-9_]/g, "_")
      }_ENABLE 1`
    )
    .join("\n");

  const credentialsContent = `/**
 * Generated by RitaWapp Build Toolchain v1.0.1
 */
#ifndef RITAWAPP_CREDENTIALS_H
#define RITAWAPP_CREDENTIALS_H

#include <stdint.h>
#include <windows.h>

#define RITA_APP_NAME "${cfg.app.name}"
#define RITA_APP_DISPLAY_NAME "${cfg.app.displayName}"
#define RITA_APP_VERSION "${cfg.app.version}"
#define RITA_APP_ID "${cfg.app.appId}"
#define RITA_APP_ICON "${cfg.app.appIcon || "app.ico"}"
#define RITA_BUNDLE_NAME "Rita.W.app"
#define RITA_REPO_URL "${cfg.repoUrl || ""}"

#define RITA_ASSETS_MOD ${cfg.assetsMod ? 1 : 0}
#define RITA_APP_BROWSER_MODE "${cfg.compiler.appBrowserMode}"

#define RITA_WINDOW_WIDTH ${cfg.window.width}
#define RITA_WINDOW_HEIGHT ${cfg.window.height}
#define RITA_WINDOW_MIN_WIDTH ${cfg.window.minWidth || 400}
#define RITA_WINDOW_MIN_HEIGHT ${cfg.window.minHeight || 300}
#define RITA_WINDOW_RESIZABLE ${cfg.window.resizable !== false ? 1 : 0}
#define RITA_WINDOW_FRAMELESS ${cfg.window.frameless ? 1 : 0}
#define RITA_WINDOW_TRANSPARENT ${cfg.window.transparent ? 1 : 0}
#define RITA_WINDOW_CENTER ${cfg.window.center !== false ? 1 : 0}

#ifndef RITA_TRAY_ENABLE
#define RITA_TRAY_ENABLE ${cfg.tray.enable ? 1 : 0}
#endif
#define RITA_TRAY_TOOLTIP "${cfg.tray.tooltip || cfg.window.title}"
#define RITA_TRAY_HIDE_ON_MINIMIZE ${cfg.tray.hideToTrayOnMinimize ? 1 : 0}

#define RITA_INSTALLER_TITLE "${cfg.installer.title}"
#define RITA_INSTALLER_SUBTITLE "${cfg.installer.subtitle}"
#define RITA_INSTALLER_WIDTH ${cfg.installer.width}
#define RITA_INSTALLER_HEIGHT ${cfg.installer.height}
#define RITA_INSTALLER_BG_COLOR RGB(${bg.r}, ${bg.g}, ${bg.b})
#define RITA_INSTALLER_ACCENT_COLOR RGB(${accent.r}, ${accent.g}, ${accent.b})
#define RITA_INSTALLER_TEXT_COLOR RGB(${text.r}, ${text.g}, ${text.b})
#define RITA_INSTALLER_ACCENT_HEIGHT ${cfg.installer.accentHeight}

static const uint8_t RITA_AES_KEY[32] = {
${keyCArray}
};

${moduleMacros}

#endif // RITAWAPP_CREDENTIALS_H
`;

  // Write credentials into project .dev directory
  const projectCredsPath = `${projectDevDir}/app_credentials.h`;
  await Deno.writeTextFile(projectCredsPath, credentialsContent);

  // Sync to framework directory if possible
  try {
    await Deno.writeTextFile(
      `${frameworkDevDir}/app_credentials.h`,
      credentialsContent,
    );
    const frameworkCredsDir = `${frameworkRoot}/Core/runtime/core`.replaceAll(
      "\\",
      "/",
    );
    await Deno.mkdir(frameworkCredsDir, { recursive: true });
    await Deno.writeTextFile(
      `${frameworkCredsDir}/app_credentials.h`,
      credentialsContent,
    );
  } catch {
    // Non-fatal if framework directory is read-only
  }

  // 2. Locate or bundle frontend
  let inputHtml = `${projectDir}/index.html`.replaceAll("\\", "/");
  try {
    const vueAppEntry = `${projectDir}/src/App.vue`.replaceAll("\\", "/");
    const statVue = await Deno.stat(vueAppEntry);
    if (statVue.isFile) {
      logger.info(`Compiling Vue 3 SFC frontend (${vueAppEntry})...`);
      const compiledHtml = await compileVueProject(projectDir);
      inputHtml = compiledHtml.replaceAll("\\", "/");
    }
  } catch {
    // Not a Vue project or Vue entry not found
  }

  try {
    const distHtml = `${projectDir}/dist/index.html`.replaceAll("\\", "/");
    const stat = await Deno.stat(distHtml);
    if (stat.isFile) inputHtml = distHtml;
  } catch {
    // fallback
  }

  try {
    await Deno.stat(inputHtml);
  } catch {
    inputHtml = `${frameworkRoot}/Core/templates/vanilla/index.html`.replaceAll(
      "\\",
      "/",
    );
  }

  // 3. Encrypt into Rita.W.app container
  const bundleDest = cfg.assetsMod
    ? `${distBinDir}/data/Rita.W.app`
    : `${distBinDir}/Rita.W.app`;
  if (cfg.assetsMod) {
    await Deno.mkdir(`${distBinDir}/data`, { recursive: true });
    await Deno.mkdir(`${distBinDir}/data/assets`, { recursive: true });
  }

  if (!options.isDev) {
    logger.info(`Encrypting bundle: ${inputHtml} -> ${bundleDest}`);
    const packerExe = `${frameworkRoot}/Core/runtime/core/packer.exe`
      .replaceAll("\\", "/");
    const packerSrc = `${frameworkRoot}/Core/runtime/core/packer.c`.replaceAll(
      "\\",
      "/",
    );

    // Compile packer.exe if missing
    try {
      await Deno.stat(packerExe);
    } catch {
      logger.info(`Compiling packer utility...`);
      const pcmd = new Deno.Command("gcc", {
        args: ["-Os", packerSrc, "-o", packerExe, "-lbcrypt"],
        stdout: "inherit",
        stderr: "inherit",
      });
      const pres = await pcmd.output();
      if (pres.code !== 0) {
        throw new BuildError("Failed to compile packer utility.");
      }
    }

    const enabledMap: Record<string, boolean> = {};
    for (const m of Object.keys(INTEGRATED_MODULES)) {
      enabledMap[m] = resolved.enabled.includes(m as any);
    }
    let htmlContent = await Deno.readTextFile(inputHtml);
    const modConfigScript = `<script>window.__RWA_ENABLED_MODULES__ = ${
      JSON.stringify(enabledMap)
    };</script>`;
    if (!htmlContent.includes("__RWA_ENABLED_MODULES__")) {
      htmlContent = htmlContent.includes("<head>")
        ? htmlContent.replace("<head>", `<head>\n  ${modConfigScript}`)
        : `${modConfigScript}\n${htmlContent}`;
    }
    const tempHtml = `${frameworkDevDir}/bundle_${Date.now()}.html`;
    await Deno.writeTextFile(tempHtml, htmlContent);

    const packCmd = new Deno.Command(packerExe, {
      args: ["encrypt", tempHtml, bundleDest, aesKey],
      stdout: "inherit",
      stderr: "inherit",
    });
    const packRes = await packCmd.output();
    try {
      await Deno.remove(tempHtml);
    } catch {}
    if (packRes.code !== 0) {
      throw new BuildError(`Packer failed with exit code ${packRes.code}`);
    }
  } else {
    logger.info(
      `Dev mode: skipping bundle encryption (frontend served dynamically via dev server)`,
    );
    try {
      await Deno.writeTextFile(bundleDest, "RWAP_DEV_MODE");
    } catch {}
  }

  // 4. Precompile SQLite & Mongoose engines
  const extraObjects: string[] = [];
  if (resolved.requiresSqlite) {
    const sqliteObj = `${frameworkDevDir}/sqlite3.o`;
    const sqliteSrc = `${frameworkRoot}/Core/runtime/sqlite/sqlite3.c`
      .replaceAll("\\", "/");
    let needsCompile = true;
    try {
      const stat = await Deno.stat(sqliteObj);
      if (stat.isFile) needsCompile = false;
    } catch {}

    if (needsCompile) {
      logger.info(`Compiling SQLite3 engine...`);
      const cmd = new Deno.Command("gcc", {
        args: [
          "-Os",
          "-c",
          sqliteSrc,
          "-o",
          sqliteObj,
          "-DSQLITE_THREADSAFE=1",
          "-DSQLITE_ENABLE_JSON1",
          "-DSQLITE_ENABLE_FTS5",
          "-DSQLITE_TEMP_STORE=3",
          "-w",
        ],
        stdout: "inherit",
        stderr: "inherit",
      });
      const res = await cmd.output();
      if (res.code !== 0) throw new BuildError("SQLite3 compilation failed.");
    }
    extraObjects.push(sqliteObj);
  }

  if (resolved.requiresMongoose) {
    const mongooseObj = `${frameworkDevDir}/mongoose.o`;
    const mongooseSrc = `${frameworkRoot}/Core/runtime/mongoose/mongoose.c`
      .replaceAll("\\", "/");
    let needsCompile = true;
    try {
      const stat = await Deno.stat(mongooseObj);
      if (stat.isFile) needsCompile = false;
    } catch {}

    if (needsCompile) {
      logger.info(`Compiling Mongoose networking engine...`);
      const cmd = new Deno.Command("gcc", {
        args: ["-Os", "-c", mongooseSrc, "-o", mongooseObj, "-w"],
        stdout: "inherit",
        stderr: "inherit",
      });
      const res = await cmd.output();
      if (res.code !== 0) throw new BuildError("Mongoose compilation failed.");
    }
    extraObjects.push(mongooseObj);
  }

  // 5. Gather C Sources
  const fw = frameworkRoot.replaceAll("\\", "/");
  const sources: string[] = [
    `${fw}/Core/runtime/core/main.c`,
    `${fw}/Core/runtime/embed/webview2_loader_embed.c`,
    `${fw}/Core/runtime/rpc/ritawapp_modules.c`,
  ];

  if (resolved.requiresSqlite) {
    sources.push(`${fw}/Core/runtime/sqlite/rita_sqlite.c`);
  }
  if (resolved.requiresMongoose) {
    sources.push(`${fw}/Core/runtime/mongoose/rita_mongoose_net.c`);
  }

  // Integrated module C files
  for (const mod of resolved.enabled) {
    const modDir = `${fw}/Core/modules/integrated/${mod}`;
    try {
      for await (const entry of Deno.readDir(modDir)) {
        if (entry.isFile && entry.name.endsWith(".c")) {
          sources.push(`${modDir}/${entry.name}`);
        }
      }
    } catch {
      // pure TS module (like path or fetch)
    }
  }

  // 5a. Scan developer custom modules (custom_module/ or custom_modules/)
  const isAsciiProject = [...projectDir].every((c) => c.charCodeAt(0) <= 127);
  const customDirs = [
    `${projectDir}/custom_module`,
    `${projectDir}/custom_modules`,
  ];
  const customIncludeFlags: string[] = [];
  for (const cDir of customDirs) {
    try {
      const st = await Deno.stat(cDir);
      if (st.isDirectory) {
        if (isAsciiProject) {
          customIncludeFlags.push(`-I${cDir.replaceAll("\\", "/")}`);
        }
        for await (const entry of Deno.readDir(cDir)) {
          if (entry.isFile && entry.name.endsWith(".c")) {
            sources.push(`${cDir}/${entry.name}`.replaceAll("\\", "/"));
            logger.info(`Included custom module C source: ${entry.name}`);
          }
        }
      }
    } catch {
      // directory does not exist or inaccessible
    }
  }

  // 5b. Compile Windows application icon resource if present
  const iconCandidates = [
    `${projectDir}/app.ico`,
    `${projectDir}/public/app.ico`,
    `${projectDir}/dist/app.ico`,
    `${frameworkRoot}/Core/templates/vanilla/app.ico`,
  ];
  let appIconPath: string | null = null;
  for (const ic of iconCandidates) {
    try {
      const st = await Deno.stat(ic);
      if (st.isFile) {
        appIconPath = ic.replaceAll("\\", "/");
        break;
      }
    } catch {}
  }

  if (appIconPath) {
    try {
      await Deno.copyFile(appIconPath, `${distBinDir}/app.ico`);
    } catch {}

    const iconRcPath = `${frameworkDevDir}/app_icon.rc`;
    const iconObjPath = `${frameworkDevDir}/app_icon.o`;
    const rcContent = `1 ICON "${appIconPath}"\n`;
    await Deno.writeTextFile(iconRcPath, rcContent);
    try {
      const wcmd = new Deno.Command("windres", {
        args: ["-i", iconRcPath, "-o", iconObjPath],
      });
      const wres = await wcmd.output();
      if (wres.code === 0) {
        extraObjects.push(iconObjPath);
      }
    } catch {
      // Windres optional fallback
    }
  }

  // 6. Compile Final Native Windows Executable
  const targetExe = `${distBinDir}/${cfg.app.name}.exe`;
  const webuiLib = `${fw}/Core/runtime/webui/lib/libwebui-2-static.a`;
  const webuiInc = `-I${fw}/Core/runtime/webui/include`;

  const linkFlags = [
    "-mwindows",
    "-lbcrypt",
    "-ldwmapi",
    "-lcomctl32",
    "-lwininet",
    "-lurlmon",
    "-lws2_32",
    "-luser32",
    "-lgdi32",
    "-lole32",
    "-liphlpapi",
    "-lshell32",
    "-luuid",
    "-lstdc++",
  ];

  const devFlags = options.isDev ? ["-DRITAWAPP_DEV=1"] : [];

  const incProjectFlags = isAsciiProject
    ? [`-I${projectDevDir}`, `-I${projectDir}`, ...customIncludeFlags]
    : [...customIncludeFlags];

  const tempExe = `${frameworkDevDir}/build_${Date.now()}.exe`;

  const gccArgs = [
    "-Os",
    "-Wall",
    "-Wextra",
    `-I${frameworkDevDir}`,
    ...incProjectFlags,
    `-I${fw}/Core`,
    `-I${fw}`,
    `-I${fw}/Core/runtime`,
    `-I${fw}/Core/runtime/sqlite`,
    `-I${fw}/Core/runtime/rpc`,
    `-I${fw}/Core/runtime/core`,
    `-I${fw}/Core/runtime/mongoose`,
    webuiInc,
    ...devFlags,
    ...sources,
    ...extraObjects,
    webuiLib,
    "-o",
    tempExe,
    ...linkFlags,
    ...cfg.compiler.extraFlags,
  ];

  logger.info(`Compiling binary with MinGW GCC: ${targetExe}`);
  const gccCmd = new Deno.Command("gcc", {
    args: gccArgs,
    stdout: "inherit",
    stderr: "inherit",
  });
  const gccRes = await gccCmd.output();
  if (gccRes.code !== 0) {
    throw new BuildError(
      `MinGW GCC compilation failed with exit code ${gccRes.code}`,
    );
  }

  // Safely copy executable to final destination (supports Arabic and Unicode folder paths)
  try {
    await Deno.copyFile(tempExe, targetExe);
  } catch (err: unknown) {
    if (String(err).includes("os error 32") || String(err).includes("used by another process")) {
      const exeName = basename(targetExe);
      try {
        const killCmd = new Deno.Command("taskkill", {
          args: ["/F", "/IM", exeName, "/T"],
          stdout: "null",
          stderr: "null",
        });
        await killCmd.output();
        await new Promise((r) => setTimeout(r, 250));
        await Deno.copyFile(tempExe, targetExe);
      } catch {
        throw err;
      }
    } else {
      throw err;
    }
  }
  try {
    await Deno.remove(tempExe);
  } catch {}

  // Sync dist JS bundles into dist/bin/
  const distDir = `${projectDir}/dist`.replaceAll("\\", "/");
  for (const f of ["app.bundle.js", "vue.esm-browser.js", "RitaWapp.js", "ritawapp.modules.js"]) {
    try {
      await Deno.copyFile(`${distDir}/${f}`, `${distBinDir}/${f}`);
    } catch {}
  }

  // 7. Measure Output Sizes
  const exeStat = await Deno.stat(targetExe);
  const bundleStat = await Deno.stat(bundleDest);

  logger.banner("RitaWapp Build Summary");
  logger.success(
    `Executable : ${targetExe} (${(exeStat.size / 1024 / 1024).toFixed(2)} MB)`,
  );
  logger.success(
    `Container  : ${bundleDest} (${(bundleStat.size / 1024).toFixed(2)} KB)`,
  );
  logger.success(
    `Modules    : ${resolved.enabled.length} enabled [${
      resolved.enabled.join(", ")
    }]`,
  );
  logger.divider();

  return {
    exePath: targetExe,
    bundlePath: bundleDest,
    appName: cfg.app.name,
  };
}
